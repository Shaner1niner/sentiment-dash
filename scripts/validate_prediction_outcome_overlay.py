from __future__ import annotations

"""Validate the prediction outcome overlay handoff JSON.

This script is read-only. It checks that sentiment-dash can locate and parse
the prediction outcome overlay generated by SETA_Prediction_Intelligence_Engine.
"""

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any


ENV_VAR = "SETA_PREDICTION_OUTCOME_OVERLAY_JSON"

REQUIRED_METADATA_FIELDS = {
    "row_count",
    "resolved_count",
    "pending_count",
    "called_evaluated_count",
    "correct_count",
    "incorrect_count",
    "no_call_count",
    "selective_accuracy",
    "accuracy_on_all_resolved",
    "generated_at",
    "predictions_table",
}

REQUIRED_ROW_FIELDS = {
    "term",
    "prediction_date",
    "horizon_days",
    "prediction",
    "prediction_label",
    "actual",
    "actual_label",
    "is_correct",
    "confidence",
    "call_status",
    "outcome_status",
    "model_version",
    "run_id",
}


def load_overlay(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Prediction outcome overlay not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Overlay root must be a JSON object.")
    return data


def validate_overlay(data: dict[str, Any]) -> dict[str, Any]:
    metadata = data.get("metadata")
    rows = data.get("rows")

    failures: list[str] = []
    warnings: list[str] = []

    if not isinstance(metadata, dict):
        failures.append("metadata must be an object")
        metadata = {}

    if not isinstance(rows, list):
        failures.append("rows must be a list")
        rows = []

    missing_metadata = sorted(REQUIRED_METADATA_FIELDS - set(metadata))
    if missing_metadata:
        failures.append(f"missing metadata fields: {', '.join(missing_metadata)}")

    row_count = metadata.get("row_count")
    if isinstance(row_count, int) and row_count != len(rows):
        failures.append(f"metadata.row_count={row_count} but rows length={len(rows)}")

    if len(rows) == 0:
        warnings.append("overlay has zero rows")

    missing_row_fields: dict[int, list[str]] = {}
    for idx, row in enumerate(rows[:25]):
        if not isinstance(row, dict):
            failures.append(f"row {idx} must be an object")
            continue
        missing = sorted(REQUIRED_ROW_FIELDS - set(row))
        if missing:
            missing_row_fields[idx] = missing

    if missing_row_fields:
        preview = "; ".join(
            f"row {idx}: {', '.join(fields)}"
            for idx, fields in list(missing_row_fields.items())[:5]
        )
        failures.append(f"missing row fields: {preview}")

    selective_accuracy = metadata.get("selective_accuracy")
    if selective_accuracy is not None:
        try:
            value = float(selective_accuracy)
            if value < 0 or value > 1:
                failures.append("metadata.selective_accuracy must be between 0 and 1")
        except (TypeError, ValueError):
            failures.append("metadata.selective_accuracy must be numeric or null")

    return {
        "valid": not failures,
        "failures": failures,
        "warnings": warnings,
        "row_count": metadata.get("row_count"),
        "resolved_count": metadata.get("resolved_count"),
        "pending_count": metadata.get("pending_count"),
        "called_evaluated_count": metadata.get("called_evaluated_count"),
        "no_call_count": metadata.get("no_call_count"),
        "selective_accuracy": metadata.get("selective_accuracy"),
        "accuracy_on_all_resolved": metadata.get("accuracy_on_all_resolved"),
        "generated_at": metadata.get("generated_at"),
        "predictions_table": metadata.get("predictions_table"),
    }


def render_report(report: dict[str, Any], *, path: Path) -> str:
    lines = [
        "Prediction Outcome Overlay Contract v1",
        "=" * 80,
        f"path: {path}",
        f"valid: {report['valid']}",
        f"row_count: {report.get('row_count')}",
        f"resolved_count: {report.get('resolved_count')}",
        f"pending_count: {report.get('pending_count')}",
        f"called_evaluated_count: {report.get('called_evaluated_count')}",
        f"no_call_count: {report.get('no_call_count')}",
        f"selective_accuracy: {report.get('selective_accuracy')}",
        f"accuracy_on_all_resolved: {report.get('accuracy_on_all_resolved')}",
        f"generated_at: {report.get('generated_at')}",
        f"predictions_table: {report.get('predictions_table')}",
    ]

    if report["warnings"]:
        lines.append("warnings:")
        lines.extend(f"  - {warning}" for warning in report["warnings"])

    if report["failures"]:
        lines.append("failures:")
        lines.extend(f"  - {failure}" for failure in report["failures"])

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate prediction outcome overlay JSON.")
    parser.add_argument(
        "--path",
        type=Path,
        default=None,
        help=f"Overlay JSON path. Defaults to ${ENV_VAR}.",
    )
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    raw_path = args.path or os.environ.get(ENV_VAR)
    if not raw_path:
        print(f"Missing overlay path. Set {ENV_VAR} or pass --path.", file=sys.stderr)
        return 2

    path = Path(raw_path)
    try:
        report = validate_overlay(load_overlay(path))
    except Exception as exc:
        report = {
            "valid": False,
            "failures": [str(exc)],
            "warnings": [],
            "row_count": None,
            "resolved_count": None,
            "pending_count": None,
            "called_evaluated_count": None,
            "no_call_count": None,
            "selective_accuracy": None,
            "accuracy_on_all_resolved": None,
            "generated_at": None,
            "predictions_table": None,
        }

    if args.json:
        print(json.dumps(report, indent=2, default=str))
    else:
        print(render_report(report, path=path))

    return 0 if report["valid"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
